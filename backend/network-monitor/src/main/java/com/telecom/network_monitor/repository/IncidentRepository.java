package com.telecom.network_monitor.repository;

import com.telecom.network_monitor.entity.Incident;
import com.telecom.network_monitor.enums.IncidentSeverity;
import com.telecom.network_monitor.enums.IncidentStatus;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.JpaSpecificationExecutor;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import java.util.Collection;
import java.util.List;
import java.util.Optional;

public interface IncidentRepository extends JpaRepository<Incident, Long>, JpaSpecificationExecutor<Incident> {

    List<Incident> findByDeletedFalse();

    List<Incident> findByDeletedTrue();

    List<Incident> findByNodeIdAndDeletedFalse(Long nodeId);

    List<Incident> findByStatusAndDeletedFalse(IncidentStatus status);

    Optional<Incident> findByIdAndDeletedTrue(Long id);

    Page<Incident> findByDeletedFalse(Pageable pageable);

    Page<Incident> findByStatusAndDeletedFalse(IncidentStatus status, Pageable pageable);

    long countByDeletedFalse();

    long countByDeletedTrue();

    long countByStatusAndDeletedFalse(IncidentStatus status);

    long countBySeverityAndDeletedFalse(IncidentSeverity severity);

    long countBySeverityAndStatusInAndDeletedFalse(IncidentSeverity severity, Collection<IncidentStatus> statuses);

    List<Incident> findByDeletedFalseAndResolvedAtIsNotNull();

    /** Incidents opened or resolved since {@code from}, with their node, for analytics. */
    @Query("""
            select i from Incident i join fetch i.node
            where i.deleted = false and (i.createdAt >= :from or i.resolvedAt >= :from)
            """)
    List<Incident> findActiveSince(@Param("from") java.time.LocalDateTime from);

    /** Used by the demo-data seeder to create realistic history. */
    @org.springframework.data.jpa.repository.Modifying
    @Query("update Incident i set i.createdAt = :at where i.id = :id")
    int backdateCreatedAt(@Param("id") Long id, @Param("at") java.time.LocalDateTime at);

    /** Unresolved incidents the outage detector opened for a node. */
    List<Incident> findByNodeIdAndAutoGeneratedTrueAndDeletedFalseAndStatusIn(Long nodeId, Collection<IncidentStatus> statuses);

    /** Open incident count per node, as [nodeId, count] rows, for the given nodes. */
    @Query("""
            select i.node.id, count(i) from Incident i
            where i.deleted = false and i.status in :statuses and i.node.id in :nodeIds
            group by i.node.id
            """)
    List<Object[]> countOpenByNodeIds(@Param("nodeIds") Collection<Long> nodeIds,
                                      @Param("statuses") Collection<IncidentStatus> statuses);
}