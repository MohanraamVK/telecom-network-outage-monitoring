package com.telecom.network_monitor.service;

import com.telecom.network_monitor.dto.IncidentDTO;
import com.telecom.network_monitor.dto.IncidentEventDTO;
import com.telecom.network_monitor.dto.IncidentRequestDTO;
import com.telecom.network_monitor.dto.PageResponse;
import com.telecom.network_monitor.entity.Incident;
import com.telecom.network_monitor.entity.IncidentEvent;
import com.telecom.network_monitor.entity.Node;
import com.telecom.network_monitor.enums.IncidentEventType;
import com.telecom.network_monitor.enums.IncidentSeverity;
import com.telecom.network_monitor.enums.IncidentStatus;
import com.telecom.network_monitor.exception.BadRequestException;
import com.telecom.network_monitor.exception.ResourceNotFoundException;
import com.telecom.network_monitor.realtime.LiveEventPublisher;
import com.telecom.network_monitor.repository.IncidentEventRepository;
import com.telecom.network_monitor.repository.IncidentRepository;
import com.telecom.network_monitor.repository.NodeRepository;
import com.telecom.network_monitor.search.IncidentSearchCriteria;
import com.telecom.network_monitor.search.SortSupport;
import com.telecom.network_monitor.security.CurrentUser;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.data.jpa.domain.Specification;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Clock;
import java.time.LocalDateTime;
import java.util.Arrays;
import java.util.EnumSet;
import java.util.List;
import java.util.Set;

@Service
@Transactional(readOnly = true)
public class IncidentService {

    public static final Set<IncidentStatus> UNRESOLVED = EnumSet.of(IncidentStatus.OPEN, IncidentStatus.IN_PROGRESS);

    private static final Set<String> SORTABLE = Set.of(
            "id", "createdAt", "updatedAt", "resolvedAt", "status", "severity", "description");

    private final IncidentRepository incidentRepository;
    private final NodeRepository nodeRepository;
    private final IncidentEventRepository eventRepository;
    private final LiveEventPublisher liveEvents;
    private final Clock clock;

    @Autowired
    public IncidentService(IncidentRepository incidentRepository,
                           NodeRepository nodeRepository,
                           IncidentEventRepository eventRepository,
                           LiveEventPublisher liveEvents) {
        this(incidentRepository, nodeRepository, eventRepository, liveEvents, Clock.systemDefaultZone());
    }

    /** Visible for tests, so timestamps can be asserted deterministically. */
    IncidentService(IncidentRepository incidentRepository,
                    NodeRepository nodeRepository,
                    IncidentEventRepository eventRepository,
                    LiveEventPublisher liveEvents,
                    Clock clock) {
        this.incidentRepository = incidentRepository;
        this.nodeRepository = nodeRepository;
        this.eventRepository = eventRepository;
        this.liveEvents = liveEvents;
        this.clock = clock;
    }

    // ------------------------------------------------------------------ commands

    @Transactional
    public IncidentDTO createIncident(Long nodeId, IncidentRequestDTO dto) {
        Node node = nodeRepository.findById(nodeId)
                .filter(n -> !n.isDeleted())
                .orElseThrow(() -> new ResourceNotFoundException("Node not found or is deleted with id: " + nodeId));

        IncidentStatus status = parseIncidentStatus(dto.getStatus());

        Incident incident = new Incident();
        incident.setDescription(dto.getDescription().trim());
        incident.setSeverity(parseIncidentSeverity(dto.getSeverity()));
        incident.setStatus(status);
        incident.setNode(node);
        incident.setDeleted(false);

        if (status.isResolved()) {
            incident.setResolvedAt(now());
        }

        Incident saved = incidentRepository.save(incident);
        record(saved, IncidentEventType.CREATED, null, status,
                "Incident raised with severity " + saved.getSeverity(), CurrentUser.username());
        liveEvents.incidentChanged(saved.getId(), "created");
        return convertToDTO(saved);
    }

    /** Opened by the outage detector when a node stops sending heartbeats. */
    @Transactional
    public Incident openAutoIncident(Node node, String description, IncidentSeverity severity) {
        Incident incident = new Incident();
        incident.setDescription(description);
        incident.setSeverity(severity);
        incident.setStatus(IncidentStatus.OPEN);
        incident.setNode(node);
        incident.setAutoGenerated(true);

        Incident saved = incidentRepository.save(incident);
        record(saved, IncidentEventType.AUTO_DETECTED, null, IncidentStatus.OPEN, description, CurrentUser.MONITOR);
        liveEvents.incidentChanged(saved.getId(), "created");
        return saved;
    }

    /** Resolves the detector's open incidents for a node once its heartbeat is back. */
    @Transactional
    public int autoResolveForNode(Long nodeId, String message) {
        List<Incident> open = incidentRepository
                .findByNodeIdAndAutoGeneratedTrueAndDeletedFalseAndStatusIn(nodeId, UNRESOLVED);

        for (Incident incident : open) {
            IncidentStatus from = incident.getStatus();
            incident.setStatus(IncidentStatus.RESOLVED);
            incident.setResolvedAt(now());
            incidentRepository.save(incident);
            record(incident, IncidentEventType.AUTO_RESOLVED, from, IncidentStatus.RESOLVED, message, CurrentUser.MONITOR);
            liveEvents.incidentChanged(incident.getId(), "updated");
        }
        return open.size();
    }

    @Transactional
    public IncidentDTO updateIncidentStatus(Long incidentId, String newStatus) {
        Incident incident = findActive(incidentId);

        IncidentStatus current = incident.getStatus();
        IncidentStatus next = parseIncidentStatus(newStatus);

        if (current != null && !current.canTransitionTo(next)) {
            throw new BadRequestException(
                    "Cannot change incident status from " + current + " to " + next
                            + (current == IncidentStatus.CLOSED
                            ? ". Closed incidents are final; raise a new incident instead."
                            : ". Allowed: " + current.allowedNextStatuses()));
        }

        if (current == next) {
            return convertToDTO(incident);
        }

        if (next.isResolved() && incident.getResolvedAt() == null) {
            // First time the outage is over: this closes the MTTR measurement window.
            incident.setResolvedAt(now());
        } else if (!next.isResolved()) {
            // Re-opened: the outage is ongoing again.
            incident.setResolvedAt(null);
        }

        incident.setStatus(next);
        Incident updated = incidentRepository.save(incident);
        record(updated, IncidentEventType.STATUS_CHANGED, current, next, null, CurrentUser.username());
        liveEvents.incidentChanged(updated.getId(), "updated");

        return convertToDTO(updated);
    }

    @Transactional
    public IncidentEventDTO addNote(Long incidentId, String message) {
        Incident incident = findActive(incidentId);
        IncidentEvent event = record(incident, IncidentEventType.NOTE, null, null,
                message.trim(), CurrentUser.username());
        liveEvents.incidentChanged(incident.getId(), "note");
        return IncidentEventDTO.from(event);
    }

    @Transactional
    public String deleteIncident(Long incidentId) {
        Incident incident = incidentRepository.findById(incidentId)
                .orElseThrow(() -> new ResourceNotFoundException("Incident not found with id: " + incidentId));

        if (incident.isDeleted()) {
            return "Incident already deleted";
        }

        incident.setDeleted(true);
        incidentRepository.save(incident);
        record(incident, IncidentEventType.DELETED, null, null, null, CurrentUser.username());
        liveEvents.incidentChanged(incident.getId(), "deleted");

        return "Incident soft deleted successfully!";
    }

    @Transactional
    public String restoreIncident(Long incidentId) {
        Incident incident = incidentRepository.findById(incidentId)
                .orElseThrow(() -> new ResourceNotFoundException("Incident not found with id: " + incidentId));

        if (!incident.isDeleted()) {
            return "Incident is already active";
        }

        if (incident.getNode() != null && incident.getNode().isDeleted()) {
            throw new BadRequestException("Cannot restore incident because its node is deleted. Restore the node first.");
        }

        incident.setDeleted(false);
        incidentRepository.save(incident);
        record(incident, IncidentEventType.RESTORED, null, null, null, CurrentUser.username());
        liveEvents.incidentChanged(incident.getId(), "restored");

        return "Incident restored successfully!";
    }

    // ------------------------------------------------------------------ queries

    public IncidentDTO getIncidentById(Long incidentId) {
        return convertToDTO(incidentRepository.findById(incidentId)
                .orElseThrow(() -> new ResourceNotFoundException("Incident not found with id: " + incidentId)));
    }

    public List<IncidentEventDTO> getTimeline(Long incidentId) {
        if (!incidentRepository.existsById(incidentId)) {
            throw new ResourceNotFoundException("Incident not found with id: " + incidentId);
        }
        return eventRepository.findByIncidentIdOrderByCreatedAtAscIdAsc(incidentId)
                .stream()
                .map(IncidentEventDTO::from)
                .toList();
    }

    public List<IncidentEventDTO> getRecentActivity(int limit) {
        int safeLimit = Math.min(Math.max(limit, 1), 100);
        return eventRepository.findAllByOrderByCreatedAtDescIdDesc(PageRequest.of(0, safeLimit))
                .stream()
                .map(IncidentEventDTO::from)
                .toList();
    }

    /** Server-side search, filter, sort and pagination. */
    public PageResponse<IncidentDTO> search(IncidentSearchCriteria criteria, int page, int size, String sort) {
        Pageable pageable = SortSupport.pageable(page, size, sort, SORTABLE, "createdAt,desc");

        Sort.Order severityOrder = pageable.getSort().getOrderFor("severity");
        Specification<Incident> spec;
        if (severityOrder != null) {
            // Rank-based ordering is applied inside the specification instead
            spec = criteria.toSpecification(severityOrder.getDirection());
            pageable = PageRequest.of(pageable.getPageNumber(), pageable.getPageSize());
        } else {
            spec = criteria.toSpecification();
        }

        Page<IncidentDTO> result = incidentRepository.findAll(spec, pageable).map(this::convertToDTO);
        return PageResponse.of(result);
    }

    public List<IncidentDTO> getAllIncidents(IncidentStatus status) {
        List<Incident> incidents = status != null
                ? incidentRepository.findByStatusAndDeletedFalse(status)
                : incidentRepository.findByDeletedFalse();

        return incidents.stream().map(this::convertToDTO).toList();
    }

    public Page<IncidentDTO> getAllIncidentsPaginated(IncidentStatus status, Pageable pageable) {
        Page<Incident> incidents = status != null
                ? incidentRepository.findByStatusAndDeletedFalse(status, pageable)
                : incidentRepository.findByDeletedFalse(pageable);

        return incidents.map(this::convertToDTO);
    }

    public List<IncidentDTO> getDeletedIncidents() {
        return incidentRepository.findByDeletedTrue().stream().map(this::convertToDTO).toList();
    }

    public List<IncidentDTO> getIncidentsByNode(Long nodeId) {
        return incidentRepository.findByNodeIdAndDeletedFalse(nodeId).stream().map(this::convertToDTO).toList();
    }

    // ------------------------------------------------------------------ helpers

    private Incident findActive(Long incidentId) {
        return incidentRepository.findById(incidentId)
                .filter(i -> !i.isDeleted())
                .orElseThrow(() -> new ResourceNotFoundException("Incident not found with id: " + incidentId));
    }

    private IncidentEvent record(Incident incident, IncidentEventType type, IncidentStatus from,
                                 IncidentStatus to, String message, String actor) {
        return eventRepository.save(new IncidentEvent(incident, type, from, to, message, actor, now()));
    }

    private LocalDateTime now() {
        return LocalDateTime.now(clock);
    }

    private IncidentSeverity parseIncidentSeverity(String severity) {
        try {
            return IncidentSeverity.valueOf(severity.trim().toUpperCase());
        } catch (IllegalArgumentException | NullPointerException ex) {
            throw new BadRequestException("Invalid severity. Allowed values: " + Arrays.toString(IncidentSeverity.values()));
        }
    }

    private IncidentStatus parseIncidentStatus(String status) {
        try {
            return IncidentStatus.valueOf(status.trim().toUpperCase());
        } catch (IllegalArgumentException | NullPointerException ex) {
            throw new BadRequestException("Invalid status. Allowed values: " + Arrays.toString(IncidentStatus.values()));
        }
    }

    IncidentDTO convertToDTO(Incident incident) {
        IncidentDTO dto = new IncidentDTO(
                incident.getId(),
                incident.getDescription(),
                incident.getSeverity(),
                incident.getStatus(),
                incident.getNode() != null ? incident.getNode().getId() : null,
                incident.getNode() != null ? incident.getNode().getName() : null,
                incident.isDeleted()
        );
        dto.setCreatedAt(incident.getCreatedAt());
        dto.setUpdatedAt(incident.getUpdatedAt());
        dto.setResolvedAt(incident.getResolvedAt());
        dto.setAutoGenerated(incident.isAutoGenerated());
        return dto;
    }
}
