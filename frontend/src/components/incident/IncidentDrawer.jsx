import { useCallback, useEffect, useState } from "react";
import { useLive } from "../../context/LiveContext";
import { useToast } from "../../context/ToastContext";
import { useAuth } from "../../hooks/useAuth";
import { useReload } from "../../hooks/useReload";
import { errorMessage } from "../../services/errors";
import { addNote, getIncident, getTimeline, updateIncidentStatus } from "../../services/incidentService";
import { canTransition, INCIDENT_STATUSES } from "../../utils/incidentWorkflow";
import { describeEvent, EVENT_DOT } from "../../utils/events";
import { INCIDENT_STATUS } from "../../utils/labels";
import { formatDateTime, formatDuration, formatRelative, minutesBetween } from "../../utils/time";
import { IncidentStatusBadge, SeverityBadge } from "../ui/Badge";
import Button from "../ui/Button";
import Dialog from "../ui/Dialog";
import { Spinner } from "../ui/Feedback";
import { TextArea } from "../ui/Field";

/** Side panel with an incident's details, workflow actions, notes and full timeline. */
function IncidentDrawer({ incidentId, onClose, onChanged, onDelete, onRestore }) {
  const { canEdit } = useAuth();
  const { subscribe } = useLive();
  const { showSuccess, showError } = useToast();
  const [incident, setIncident] = useState(null);
  const [timeline, setTimeline] = useState([]);
  const [note, setNote] = useState("");
  const [busy, setBusy] = useState(false);
  const [loadError, setLoadError] = useState("");

  const load = useCallback(async () => {
    try {
      const [i, t] = await Promise.all([getIncident(incidentId), getTimeline(incidentId)]);
      setIncident(i);
      setTimeline(t);
      setLoadError("");
    } catch (err) {
      setLoadError(errorMessage(err, "This incident could not be loaded."));
    }
  }, [incidentId]);

  useReload(load);

  // Someone else (or the monitor) changed this incident: refresh in place
  useEffect(
    () =>
      subscribe("incident.changed", (event) => {
        if (event?.data?.id === incidentId) load();
      }),
    [subscribe, incidentId, load]
  );

  const changeStatus = async (status) => {
    try {
      setBusy(true);
      await updateIncidentStatus(incidentId, status);
      showSuccess("Status changed", `Incident #${incidentId} is now ${INCIDENT_STATUS[status].label.toLowerCase()}`);
      await load();
      onChanged?.();
    } catch (err) {
      showError("Status not changed", errorMessage(err));
    } finally {
      setBusy(false);
    }
  };

  const submitNote = async (event) => {
    event.preventDefault();
    if (!note.trim()) return;
    try {
      setBusy(true);
      await addNote(incidentId, note.trim());
      setNote("");
      await load();
    } catch (err) {
      showError("Note not added", errorMessage(err));
    } finally {
      setBusy(false);
    }
  };

  const resolvedIn = incident?.resolvedAt ? minutesBetween(incident.createdAt, incident.resolvedAt) : null;
  const nextStatuses = incident ? INCIDENT_STATUSES.filter((s) => s !== incident.status && canTransition(incident.status, s)) : [];

  return (
    <Dialog
      open
      onClose={onClose}
      placement="right"
      width="max-w-xl"
      title={incident ? `Incident #${incident.id}` : "Incident"}
      description={incident ? incident.description : null}
      footer={
        canEdit && incident ? (
          incident.deleted ? (
            <Button onClick={() => onRestore(incident)}>Restore incident</Button>
          ) : (
            <Button variant="ghost" className="mr-auto hover:text-outage" onClick={() => onDelete(incident)}>
              Delete incident
            </Button>
          )
        ) : null
      }
    >
      {loadError ? (
        <p className="text-sm text-outage">{loadError}</p>
      ) : !incident ? (
        <div className="flex justify-center py-16">
          <Spinner className="size-6" />
        </div>
      ) : (
        <div className="space-y-8">
          <dl className="grid grid-cols-2 gap-x-6 gap-y-4 text-sm">
            <Detail label="Status"><IncidentStatusBadge status={incident.status} /></Detail>
            <Detail label="Severity"><SeverityBadge severity={incident.severity} /></Detail>
            <Detail label="Node">{incident.nodeName}</Detail>
            <Detail label="Raised by">{incident.autoGenerated ? "Outage detector" : "Operator"}</Detail>
            <Detail label="Opened">
              <span title={formatDateTime(incident.createdAt)}>{formatRelative(incident.createdAt)}</span>
            </Detail>
            <Detail label="Time to resolve">
              {resolvedIn != null ? formatDuration(resolvedIn) : incident.createdAt ? `Ongoing for ${formatDuration(minutesBetween(incident.createdAt, new Date().toISOString()))}` : "—"}
            </Detail>
          </dl>

          {canEdit && !incident.deleted ? (
            <section aria-labelledby="actions-heading">
              <h3 id="actions-heading" className="mb-2 font-display text-base font-semibold">Move to</h3>
              {nextStatuses.length ? (
                <div className="flex flex-wrap gap-2">
                  {nextStatuses.map((status) => (
                    <Button key={status} size="sm" disabled={busy} onClick={() => changeStatus(status)}>
                      {INCIDENT_STATUS[status].label}
                    </Button>
                  ))}
                </div>
              ) : (
                <p className="text-sm text-fjord-400">Closed incidents are final. Raise a new incident if the fault comes back.</p>
              )}
            </section>
          ) : null}

          <section aria-labelledby="timeline-heading">
            <h3 id="timeline-heading" className="mb-4 font-display text-base font-semibold">Timeline</h3>
            <ol className="relative ml-1 space-y-5 border-l border-fjord-700 pl-5">
              {timeline.map((event) => (
                <li key={event.id} className="relative">
                  <span className={`absolute top-1.5 -left-[25px] size-2.5 rounded-full ring-4 ring-fjord-900 ${EVENT_DOT[event.type] ?? "bg-fjord-400"}`} aria-hidden="true" />
                  <p className="text-sm text-fjord-100">
                    <span className="font-semibold">{event.actor}</span> {describeEvent(event)}
                  </p>
                  {event.message && (event.type === "NOTE" || event.type.startsWith("AUTO")) ? (
                    <p className={`mt-1 text-sm ${event.type === "NOTE" ? "rounded-md bg-fjord-850 px-3 py-2 text-fjord-100" : "text-fjord-300"}`}>
                      {event.message}
                    </p>
                  ) : null}
                  <time className="mt-0.5 block text-xs text-fjord-400" dateTime={event.createdAt} title={formatDateTime(event.createdAt)}>
                    {formatRelative(event.createdAt)}
                  </time>
                </li>
              ))}
            </ol>

            {canEdit && !incident.deleted ? (
              <form onSubmit={submitNote} className="mt-6 space-y-2">
                <TextArea
                  label="Add a note"
                  value={note}
                  onChange={(event) => setNote(event.target.value)}
                  placeholder="What did you find or do?"
                  maxLength={1000}
                />
                <div className="flex justify-end">
                  <Button type="submit" size="sm" disabled={busy || !note.trim()}>Add note</Button>
                </div>
              </form>
            ) : null}
          </section>
        </div>
      )}
    </Dialog>
  );
}

function Detail({ label, children }) {
  return (
    <div>
      <dt className="text-fjord-400">{label}</dt>
      <dd className="mt-1 text-fjord-100">{children}</dd>
    </div>
  );
}

export default IncidentDrawer;
